#!/usr/bin/env python3
"""Generate a native NaN16 phase library + exhaustive checksum guest from C LUT."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
s=list(map(int,re.search(r'nan_sine\[257\]=\{([^}]+)',(root/'include/nanlm/nan16.h').read_text())[1].split(',')))
def sine(p):
    i=p&16383
    if p&16384:i=16384-i
    k,f=divmod(i,64)
    v=s[k]+((s[k+1]-s[k])*f+32)//64 if f else s[k]
    return -v if p&32768 else v
checksum=sum((p+1)*sine(p) for p in range(65536))&0xffffffff
source='''; Generated by tools/build_phase_guest.py; NaNVM1 MUL required.
; nsin: r1=phase -> r1=signed Q15; clobbers r2..r7; r0 must be zero.
.org 0
JMP @main
nsin:
MOVI r2,16383
BOOL.8 r3,r1,r2
MOVI r2,16384
BOOL.8 r4,r1,r2
CMP r4,r0
JMP[EQ] @folded
SUB r3,r2,r3
folded:
SHR r4,r3,6
MOVI r2,63
BOOL.8 r5,r3,r2
MOVI r6,@sine_table
ADD r6,r6,r4
LD r7,r6,0
CMP r5,r0
JMP[EQ] @signed
LD r4,r6,1
SUB r4,r4,r7
MUL r4,r4,r5
ADDI r4,r4,32
SHR r4,r4,6
ADD r7,r7,r4
signed:
MOVI r2,32768
BOOL.8 r4,r1,r2
BOOL.14 r1,r7,r0
CMP r4,r0
JMP[EQ] @sine_return
SUB r1,r0,r7
sine_return:
RET
; Tail call preserves the caller link.
ncos:
MOVI r2,16384
ADD r1,r1,r2
JMP @nsin
main:
MOVI r8,0
MOVI r9,0
phase_loop:
BOOL.14 r1,r8,r0
CALL @nsin
ADDI r10,r8,1
MUL r10,r10,r1
ADD r9,r9,r10
ADDI r8,r8,1
MOVI r11,0
MOVHI r11,1
CMP r8,r11
JMP[NE] @phase_loop
'''
source+=f'MOVI r10,{checksum&65535}\nMOVHI r10,{checksum>>16}\nCMP r9,r10\nJMP[NE] @fail\n'
for ch in 'PHASE PASS\n':source+=f'MOVI r1,{ord(ch)}\nPUTC r1\n'
source+='HALT\nfail:\n'
for ch in 'PHASE FAIL\n':source+=f'MOVI r1,{ord(ch)}\nPUTC r1\n'
source+='HALT\nsine_table:\n'+''.join(f'.word {x}\n' for x in s)
(root/'guest/phase.nas').write_text(source)
